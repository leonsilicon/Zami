// Editor settings that hide Zam's own files, so the file tree shows Zami's versions
// (`*.zami.*`) and Zami's code. Neither file overrides anything of Zam's:
//
//  - VS Code: `zami.code-workspace` (VS Code reads folder settings only from
//    .vscode/settings.json, which is Zam's). Each rule hides an upstream file only while its
//    Zami version exists beside it ("hide foo.ts when foo.zami.ts exists"), so new upstream
//    files of a known type are covered automatically. Opening the folder without the
//    workspace shows everything.
//  - Zed: `.zed/settings.json`. Zed's exclusions can't depend on a sibling, so it lists every
//    upstream file that has a Zami version (regenerated by `_zami sync` and `_zami done`).
//
// Zami's overrides (the root package.json) stay visible: they're Zami's files.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import type { Project } from "#project";

export const VSCODE_WORKSPACE_PATH = "zami.code-workspace";
export const ZED_SETTINGS_PATH = ".zed/settings.json";

// A project-level value replaces each editor's defaults, so they're restated.
const VSCODE_DEFAULT_EXCLUDES: Record<string, boolean> = {
  "**/.git": true,
  "**/.svn": true,
  "**/.hg": true,
  "**/CVS": true,
  "**/.DS_Store": true,
  "**/Thumbs.db": true,
};
const ZED_DEFAULT_EXCLUSIONS = [
  "**/.git",
  "**/.svn",
  "**/.hg",
  "**/.jj",
  "**/CVS",
  "**/.DS_Store",
  "**/Thumbs.db",
  "**/.classpath",
  "**/.settings",
];

type VscodeExclude = boolean | { when: string };

function sorted<T>(entries: Iterable<[string, T]>): Record<string, T> {
  return Object.fromEntries([...entries].toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/** The generated editor settings, keyed by repo-relative path. */
export function editorSettings(project: Project): Map<string, string> {
  const overrides = new Set(project.config.overrides);
  // Only files whose Zami version exists: a component not ported yet stays visible.
  const upstream = project
    .mappings()
    .filter((mapping) => !overrides.has(mapping.upstreamPath))
    .filter((mapping) => existsSync(join(project.root, mapping.zamiPath)))
    .map((mapping) => mapping.upstreamPath);

  const excludes = new Map<string, VscodeExclude>(Object.entries(VSCODE_DEFAULT_EXCLUDES));
  for (const path of upstream) {
    const name = posix.basename(path);
    if (!path.includes("/") || path.endsWith(".d.ts")) {
      // Root files (so overrides beside them stay visible) and `.d.ts` files (whose Zami
      // name, `x.zami.d.ts`, isn't `$(basename).zami.ts`) are listed one by one.
      excludes.set(path, true);
    } else if (name.endsWith(".svelte")) {
      excludes.set("*/**/*.svelte", { when: "$(basename).svelte.zami.tsx" });
    } else {
      const dot = name.lastIndexOf(".");
      if (dot <= 0) excludes.set(`*/**/${name}`, { when: "$(basename).zami" });
      else excludes.set(`*/**/*${name.slice(dot)}`, { when: `$(basename).zami${name.slice(dot)}` });
    }
  }

  const vscode = {
    folders: [{ path: "." }],
    settings: {
      // Generated by `vpx _zami editor` (and `_zami sync`): hides Zam's files that have a Zami
      // version. Open the folder without this workspace to see everything.
      "files.exclude": sorted(excludes),
    },
  };
  const zed = {
    // Generated by `vpx _zami editor` (and `_zami sync`): hides Zam's files that have a Zami version.
    file_scan_exclusions: [...ZED_DEFAULT_EXCLUSIONS, ...upstream.toSorted()],
  };
  return new Map([
    [VSCODE_WORKSPACE_PATH, `${JSON.stringify(vscode, null, 2)}\n`],
    [ZED_SETTINGS_PATH, `${JSON.stringify(zed, null, 2)}\n`],
  ]);
}

/** Writes the editor settings (or, with `check`, only reports which are out of date). */
export function writeEditorSettings(project: Project, options: { check?: boolean } = {}): string[] {
  const stale: string[] = [];
  for (const [path, text] of editorSettings(project)) {
    const absolute = join(project.root, path);
    if (existsSync(absolute) && readFileSync(absolute, "utf8") === text) continue;
    stale.push(path);
    if (!options.check) {
      mkdirSync(dirname(absolute), { recursive: true });
      writeFileSync(absolute, text);
    }
  }
  return stale;
}
